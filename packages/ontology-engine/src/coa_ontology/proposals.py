"""Ontology proposals API.

Proposals are generated by ``/induce`` and stored in DynamoDB. Users can
list, view, accept, reject, cancel, validate, or update them.

Accept is **asynchronous** and means **publish**: ``POST /accept`` flips the
proposal to ``accepting`` and a background thread merges it onto the
namespace's newest ontology version, writing an immutable snapshot
(:mod:`coa_ontology.versions`). Serving changes only when a version is
deployed: right away when the request's ``deploy`` flag is true (default).
Clients poll ``GET /proposals/{id}`` for ``accepted`` (with
``published_version``) or ``accept_failed`` (with ``accept_error``). A failed
accept never touched serving state, so it is simply re-accepted.

A proposal that the Ontology designer opened (``studio`` on its row) is accepted as its draft: the revision
the user reviewed is published in replace mode (see :func:`_studio_publish_request`), and the
Turtle edit paths of this module stand aside for it.
"""

