# Proposal statuses come from the Smithy-generated ProposalStatus enum — the API
# contract in models/ontology-induction.smithy is the single source of truth, so
# the wire value and the stored value can never drift. Aliased here because the
# accept pipeline references a few of them constantly.
#
# ``embeddings_sync``: the pre-versioning accept pipeline set this while it waited
# for the embeddings it wrote to become searchable. Accept no longer writes
# embeddings (a deployment does), but rows left in this state still count as an
# accept in progress for the accept guard, the stale-sweep and the induction lock.
PROPOSAL_STATUS_EMBEDDINGS_SYNC = ProposalStatus.EMBEDDINGS_SYNC.value

# Terminal state for an accept whose publish failed (#456/#466/#467). Distinct
# from ``pending`` (never attempted) so the UI can say "accept failed, fix and
# retry" and the stale-sweep / accept guard can tell a broken attempt from a
# fresh proposal. A failed publish changed nothing, so re-accepting from this
# state simply publishes again.
PROPOSAL_STATUS_ACCEPT_FAILED = ProposalStatus.ACCEPT_FAILED.value

# In-progress accept states — a worker is (or was) running, so Accept is
# disabled and a new induction is blocked. Used by the accept guard, the
# stale-sweep, and the induction in-flight lock.
_ACCEPT_IN_PROGRESS_STATUSES = (
    ProposalStatus.ACCEPTING.value,
    PROPOSAL_STATUS_EMBEDDINGS_SYNC,
)

# Statuses that block starting a NEW induction in the namespace (see the
# in-flight guard in induce_catalog). Two kinds of "not finished with this one":
#
#   - unreviewed work: ``pending`` / ``updated`` / ``accept_failed``. The first
#     two preserve the original behaviour; ``accept_failed`` is included because
#     before that state existed a failed accept rolled back to ``pending``, which
#     blocked. Dropping it would remove the guard for exactly the case a user is
#     most likely to hit — accept broke, so they trigger another induction.
#   - an accept actively merging: ``accepting`` / ``embeddings_sync``. The
#     induction lock (acquire_induction_lock) is only held for the duration of an
#     INDUCTION, so without these a new induction can start while a worker is
#     mid-merge, leaving two competing structured proposals in the namespace.
PROPOSAL_STATUSES_BLOCKING_NEW_INDUCTION = (
    ProposalStatus.PENDING.value,
    ProposalStatus.UPDATED.value,
    PROPOSAL_STATUS_ACCEPT_FAILED,
    *_ACCEPT_IN_PROGRESS_STATUSES,
)

