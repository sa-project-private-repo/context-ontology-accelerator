# 409 body for an edit through the Turtle path of a proposal that the Ontology designer edits.
_STUDIO_OPEN = {
    "code": "StudioDraftOpen",
    "message": "This proposal is open in the Ontology designer; edit it there.",
}


def proposal_turtle(item: dict[str, Any], namespace: str) -> tuple[str, str]:
    """Return the ontology and R2RML Turtle an accept publishes: the steward-reviewed copy when there is one."""
    reviewed = (
        dynamo_store.get_reviewed_proposal(item["job_id"], kind="ontology", namespace=namespace)
        if hasattr(dynamo_store, "get_reviewed_proposal")
        else None
    )
    reviewed = reviewed or {}
    turtle = reviewed.get("ontology_turtle") or item.get("ontology_turtle") or ""
    # Unstructured proposals have no R2RML ("").
    r2rml = reviewed.get("r2rml_turtle") or item.get("r2rml_turtle") or ""
    return turtle, r2rml


def _publish_request(
    item: dict[str, Any],
    namespace: str,
    proposal_id: str,
    ontology_id: str,
    created_by: str,
    turtle: str,
    r2rml_turtle: str,
    title: str | None = None,
) -> version_publish.PublishRequest:
    metadata = item.get("metadata") or {}
    datasource_ids = [str(d) for d in metadata.get("datasource_ids") or []]
    # A complete table induction maps every table of its datasources, so its R2RML
    # replaces their maps in the parent version instead of adding to them.
    complete_induction = (
        metadata.get("induction_strategy") == "table_to_ontology"
        and int(metadata.get("dropped_tables_count") or 0) == 0
    )
    return version_publish.PublishRequest(
        namespace=namespace,
        ontology_id=ontology_id,
        ontology_turtle=turtle,
        r2rml_turtle=r2rml_turtle,
        source_proposal_id=proposal_id,
        created_by=created_by,
        datasource_ids=datasource_ids,
        constraint_config=metadata.get("constraint_config"),
        uri_prefix=item.get("ontology_id") or metadata.get("ontology_uri_prefix"),
        authoritative_datasources=datasource_ids if complete_induction else [],
        title=title,
    )


def _publish_title(item: dict[str, Any], namespace: str) -> str:
    """Return the title for the ontology's registry row when an accept of ``item`` leads to the first deployment.

    The proposal's stored label, else a source-appropriate default (rare: induction always sets
    one). The default title follows the namespace language, read from the namespace only on this path.
    """
    label = (item.get("metadata") or {}).get("label")
    if label is None:
        from coa_ontology.induce_catalog import namespace_language_or_404
        from coa_ontology.inducer.services.generated_text import render

        title_key = (
            "unstructured_proposal_title" if item.get("source_type") == "UNSTRUCTURED" else "structured_proposal_title"
        )
        label = render(title_key, namespace_language_or_404(namespace, _namespace_language_config()))
    return str(label)


def publish_request_for(
    item: dict[str, Any], namespace: str, proposal_id: str, ontology_id: str, created_by: str
) -> version_publish.PublishRequest:
    """Return the union-mode publish request an accept of ``item`` into ``ontology_id`` makes.

    The Ontology designer builds its draft from it (``publish.union_candidate``), so the draft starts
    as exactly what a plain accept would publish.
    """
    turtle, r2rml_turtle = proposal_turtle(item, namespace)
    return _publish_request(
        item,
        namespace,
        proposal_id,
        ontology_id,
        created_by,
        turtle,
        r2rml_turtle,
        title=_publish_title(item, namespace),
    )


def _studio_http(error: studio_draft.StudioError) -> HTTPException:
    """The HTTP error of a designer refusal: its status and ``{code, message, ...}`` detail."""
    return HTTPException(error.status, error.detail())


def _check_expected_revision(state: studio_draft.StudioState, expected_revision: int | None, action: str) -> None:
    """Refuse a write to a designer draft that does not name the revision the user reviewed.

    422 ``ExpectedRevisionRequired`` without ``expected_revision``; 409 ``DraftConflict`` (with the
    current revision) when the draft is at another one.
    """
    if expected_revision is None:
        raise HTTPException(
            422,
            {
                "code": "ExpectedRevisionRequired",
                "message": f"This proposal is open in the Ontology designer; {action} it with the "
                "expectedRevision you reviewed.",
            },
        )
    if expected_revision != state.revision:
        raise _studio_http(studio_draft.DraftConflict(state.revision))


def _studio_publish_request(
    namespace: str,
    proposal_id: str,
    state: studio_draft.StudioState,
    expected_revision: int | None,
    head: dict[str, Any] | None,
    req: version_publish.PublishRequest,
) -> version_publish.PublishRequest:
    """Turn ``req`` into the replace-mode publish of the draft revision the user reviewed, or raise the 4xx.

    422 ``ExpectedRevisionRequired`` without ``expected_revision``; 409 ``DraftConflict`` when the
    draft is at another revision; 409 ``RebaseRequired`` unless ``head`` (the newest version) is the
    version the draft was built on. The publish rechecks the base under its reservation.

    ``req`` carries the proposal's own ontology and R2RML; they go along as
    ``proposal_ontology_turtle`` / ``proposal_r2rml_turtle``, so the proposal's compiled shapes get
    the renames its draft's base kept, and an unedited draft publishes the shapes a plain accept would.
    """
    _check_expected_revision(state, expected_revision, "accept")
    head_version = int(head["version"]) if head else None
    if head_version != state.base_version:
        raise _studio_http(studio_draft.RebaseRequired(state.base_version, head_version))
    ontology_nt, r2rml_nt = studio_draft.revision_text(namespace, proposal_id, state.revision)
    return dataclasses.replace(
        req,
        ontology_turtle=ontology_nt,
        r2rml_turtle=r2rml_nt,
        mode=version_publish.REPLACE,
        expected_parent_version=state.base_version,
        authoritative_datasources=[],
        proposal_ontology_turtle=req.ontology_turtle,
        proposal_r2rml_turtle=req.r2rml_turtle,
    )


def _studio_flip_lost(namespace: str, proposal_id: str) -> HTTPException:
    """The 409 for a designer accept that lost its conditional flip: ``DraftConflict`` with the revision now."""
    try:
        state = studio_draft.require_state(studio_draft.get_proposal(namespace, proposal_id), editable=False)
    except studio_draft.StudioError as e:
        return _studio_http(e)
    return _studio_http(studio_draft.DraftConflict(state.revision))


# ── Accept (async) ──────────────────────────────────────────────────────
# Accept = publish. The handler flips the proposal to ``accepting`` and a
# daemon thread writes the next immutable ontology version (merge + snapshot +
# schema.sql generation can exceed API Gateway's 29 s integration timeout),
# then optionally starts its deployment (``coa_ontology.versions.deploy``).

# Recording the published version on the proposal is retried on a transient
# DynamoDB error; once the attempts are spent the stale-sweep fails the proposal.
_ACCEPT_FLIP_ATTEMPTS = 3
_ACCEPT_FLIP_BACKOFF_SECONDS = 1.0


def _record_published(proposal_id: str, namespace: str, version: int) -> bool:
    """Flip the proposal to ``accepted`` with ``published_version``; return whether it now is.

    Conditional on ``accepting``: a proposal the stale-sweep failed, or that another
    accept took over, is left alone. Either way the version stays published. When a
    retry fails that condition because an earlier attempt's write landed (only its
    response was lost), the proposal already reads ``accepted`` with this version,
    and that counts as success.
    """
    for attempt in range(1, _ACCEPT_FLIP_ATTEMPTS + 1):
        try:
            dynamo_store.update_proposal(
                proposal_id,
                namespace=namespace,
                status=ProposalStatus.ACCEPTED.value,
                accept_error="",
                published_version=version,
                accept_progress={"step": "publish", "state": "done"},
                expected_status=ProposalStatus.ACCEPTING.value,
            )
            return True
        except (ClientError, BotoCoreError) as e:
            if isinstance(e, ClientError) and e.response.get("Error", {}).get("Code") == (
                "ConditionalCheckFailedException"
            ):
                if attempt > 1 and _flip_landed(proposal_id, namespace, version):
                    # An earlier attempt's write landed and only its response was lost.
                    return True
                _log.warning(
                    "accept[%s]: proposal stopped being 'accepting' (swept or re-accepted) while v%d was "
                    "published; the version exists but is not deployed by this accept",
                    proposal_id,
                    version,
                )
                return False
            if attempt == _ACCEPT_FLIP_ATTEMPTS:
                _log.exception(
                    "accept[%s]: v%d is published but the proposal could not be marked accepted; "
                    "the stale-sweep will fail it and a re-accept publishes again",
                    proposal_id,
                    version,
                )
                return False
            _log.warning(
                "accept[%s]: recording v%d failed (attempt %d/%d): %s; retrying",
                proposal_id,
                version,
                attempt,
                _ACCEPT_FLIP_ATTEMPTS,
                e,
            )
            time.sleep(_ACCEPT_FLIP_BACKOFF_SECONDS * attempt)
    return False


def _flip_landed(proposal_id: str, namespace: str, version: int) -> bool:
    """Whether the proposal already reads ``accepted`` with ``published_version == version``."""
    item = dynamo_store.get_proposal_by_id(
        proposal_id, namespace=namespace, hydrate_turtle=False, hydrate_matches=False, hydrate_constraints=False
    )
    if not item or item.get("status") != ProposalStatus.ACCEPTED.value:
        return False
    published = item.get("published_version")
    return published is not None and int(published) == version


def _held(reason: str, error: Exception) -> dict[str, Any]:
    return {"reason": reason, "error": f"{type(error).__name__}: {error}"[:500]}


def _run_publish_proposal(
    proposal_id: str,
    namespace: str,
    request: version_publish.PublishRequest,
    proposal_job_id: str,
    deploy_after: bool,
) -> None:
    """Background worker for accept: publish a version, then optionally start its deployment.

    Publishing never touches serving state, so every failure lands the proposal
    in ``accept_failed`` and a re-accept simply retries. A deployment that cannot
    start (breaking metrics, another deployment running) does not fail the
    accept: the version stays PUBLISHED and the reason is recorded on the
    proposal as ``auto_deploy_held`` for the UI to surface. A deployment that
    starts is recorded as ``auto_deploy_id``.
    """

    def _heartbeat(phase: str) -> None:
        # Also called from the publish heartbeat thread. Refreshing the proposal's
        # updated_at keeps the accept stale-sweep off a publish that is still alive.
        try:
            dynamo_store.update_proposal(
                proposal_id, namespace=namespace, accept_progress={"step": "publish", "state": phase}
            )
        except Exception:  # noqa: BLE001 (heartbeat is best-effort)
            _log.warning("accept[%s]: heartbeat failed", proposal_id, exc_info=True)

    try:
        try:
            version = version_publish.publish_version(request, on_progress=_heartbeat)
        except version_publish.BootstrapPendingError:
            # An earlier bootstrap of this namespace failed after reserving; publishing again re-runs it.
            _log.info("accept[%s]: namespace not bootstrapped yet; publishing once more", proposal_id)
            version = version_publish.publish_version(request, on_progress=_heartbeat)
    except SnapshotValidationError as e:
        _accept_fail(proposal_id, namespace, f"Invalid ontology: {e}", step="publish")
        return
    except version_publish.PublishBusyError as e:
        _accept_fail(proposal_id, namespace, f"Publishing is busy: {e}", step="publish")
        return
    except version_publish.PublishStateError as e:
        _accept_fail(proposal_id, namespace, f"Operator action needed: {e}", step="publish")
        return
    except version_publish.RebaseRequiredError as e:
        # A newer version landed after the accept's own check. The code lets the client offer the rebase.
        _accept_fail(proposal_id, namespace, str(e), step="publish", code=studio_draft.RebaseRequired.code)
        return
    except version_publish.PublishError as e:  # its message says what to do
        _accept_fail(proposal_id, namespace, str(e), step="publish")
        return
    except Exception as e:  # noqa: BLE001 (surface any other failure on the proposal)
        _log.exception("accept[%s]: publish failed", proposal_id)
        _accept_fail(proposal_id, namespace, f"{type(e).__name__}: {e}", step="publish")
        return

    if not _record_published(proposal_id, namespace, version):
        return
    studio_queries.drop_draft_graph(namespace, proposal_id)
    try:
        dynamo_store.update_job_status(proposal_job_id, "ingested", namespace=namespace)
    except Exception:  # noqa: BLE001 (cosmetic: the proposal row is what the UI reads)
        _log.warning("accept[%s]: job status mirror failed (non-fatal)", proposal_id, exc_info=True)
    if not deploy_after:
        return

    outcome: dict[str, Any]
    try:
        outcome = {
            "auto_deploy_id": version_deploy.start_deployment(namespace, version, requested_by=request.created_by)
        }
    except version_deploy.BreakingMetricsError as e:
        outcome = {"auto_deploy_held": {"reason": "BREAKING_METRICS", "metrics": e.metrics}}
    except version_registry.DeployLockHeldError:
        outcome = {"auto_deploy_held": {"reason": "DEPLOY_IN_PROGRESS"}}
    except version_deploy.DeployConflictError as e:
        # Expected: e.g. a backend without ontology versions, or an ontology being deleted.
        _log.warning("accept[%s]: auto-deploy of v%d not started: %s", proposal_id, version, e)
        outcome = {"auto_deploy_held": _held("DEPLOY_FAILED_TO_START", e)}
    except Exception as e:  # noqa: BLE001 (the version is published; only the auto-deploy is held)
        _log.exception("accept[%s]: auto-deploy of v%d did not start", proposal_id, version)
        outcome = {"auto_deploy_held": _held("DEPLOY_FAILED_TO_START", e)}
    try:
        dynamo_store.update_proposal(proposal_id, namespace=namespace, **outcome)
    except Exception:  # noqa: BLE001 (a started deployment runs regardless; the row only reports it)
        _log.exception("accept[%s]: could not record the auto-deploy outcome %s", proposal_id, outcome)


def _accept_fail(proposal_id: str, namespace: str, error: str, step: str = "unknown", code: str | None = None) -> None:
    """Move a failed accept to the terminal ``accept_failed`` state.

    The user observes this via the next ``GET /proposals/{id}`` poll: the status
    is ``accept_failed`` (distinct from ``pending``, so the UI can say "accept
    failed on step X — fix and retry" rather than showing a fresh proposal) and
    ``accept_error`` carries the reason. ``accept_failed`` is re-acceptable: the
    accept guard treats it like ``pending``/``updated``, and a failed publish
    changed nothing, so a re-accept simply publishes again.

    ``step`` names the failing stage (``publish``; rows left by the pre-versioning
    pipeline carry its step names) and is recorded on ``accept_progress`` for
    diagnosis. ``code``, when given, is recorded there too (``accept_progress.code``) so a
    client can tell this failure from the others: ``RebaseRequired`` means the designer
    draft must be rebased before it is accepted again. We swallow the rollback write error
    so the worker doesn't crash on a transient DDB hiccup; the stale-sweep is the backstop
    if this write is lost.

    Error messages are truncated to 1000 chars to avoid DynamoDB
    ValidationException on large error payloads (e.g. BulkIndexError with
    embedded vectors).

    Logs at ERROR before writing. This is the single choke point for every
    terminal-failure path (invalid ontology, busy, operator action, and the
    catch-all), so logging here means a failed accept is always visible in
    CloudWatch — without it an operator only sees the route's 202 and no trace of
    why the accept never completed.

    NEVER DOWNGRADES AN ALREADY-``accepted`` PROPOSAL. A worker can outlive its
    accept: the stale-sweep flips a slow accept to ``accept_failed``, a re-accept
    then publishes and flips it to ``accepted``, and only afterwards does the first
    worker fail. Reverting the proposal then would hide its published version and
    drop it out of the call sites that select on ``status="accepted"``
    (``_generate_schema_sql``, ``list_induced_datasources`` and the
    duplicate-detection scan).

    The write is therefore conditional on the status still being non-terminal.
    When it is already ``accepted`` the status is left alone and only the
    diagnostic fields are recorded, so the failure is still greppable and
    visible on the proposal.
    """
    _log.error("accept[%s]: FAILED on step '%s': %s", proposal_id, step, str(error)[:500])
    error_msg = str(error)[:1000]
    progress = {"step": step, "state": "failed", **({"code": code} if code else {})}
    try:
        dynamo_store.update_proposal(
            proposal_id,
            namespace=namespace,
            status=PROPOSAL_STATUS_ACCEPT_FAILED,
            accept_error=error_msg,
            accept_progress=progress,
            expected_status_not="accepted",
        )
    except ClientError as e:
        if e.response.get("Error", {}).get("Code") != "ConditionalCheckFailedException":
            _log.exception("accept[%s]: failed to record accept_failed status", proposal_id)
            return
        # Already ``accepted``: another attempt published a version. Keep the status
        # and record this late failure for diagnosis only.
        _log.error(
            "accept[%s]: step '%s' failed after the proposal was already accepted; the failure is "
            "recorded for diagnosis and the published version stays as it is",
            proposal_id,
            step,
        )
        try:
            dynamo_store.update_proposal(
                proposal_id,
                namespace=namespace,
                accept_error=error_msg,
                accept_progress=progress,
            )
        except Exception:  # noqa: BLE001 — diagnostics only; the log line above stands
            _log.exception("accept[%s]: failed to record post-accept step failure", proposal_id)
    except Exception:  # noqa: BLE001
        _log.exception("accept[%s]: failed to record accept_failed status", proposal_id)


@router.post("/{proposal_id}/accept", status_code=202, response_model=AcceptProposalResponse)
def accept_proposal(
    proposal_id: str,
    body: AcceptProposalRequest | None = None,
    namespace: str = "default",
    x_coa_principal: Annotated[str | None, Header()] = None,
) -> AcceptProposalResponse:
    """Publish the proposal as the namespace's next ontology version, asynchronously.

    Returns 202 with the proposal flipped to ``accepting``. The worker merges the
    proposal onto the newest published version and writes an immutable snapshot
    (``coa_ontology.versions``); serving changes only when that version is
    deployed: immediately when ``body.deploy`` is true (the default), otherwise
    from the Versions tab. Clients poll ``GET /proposals/{id}``: ``accepted`` with
    ``published_version``, or ``accept_failed`` with ``accept_error``.

    ``body.ontology_id`` selects the target. When omitted the proposal's
    own embedded ``ontology_id`` is used (one-to-one mapping, default
    behaviour). Multiple proposals can name the same target, in which
    case their Turtle content is merged into a single per-ontology named
    graph and their proposal IDs accumulate on a single Dynamo registry
    row's ``source_proposals`` list.

    Idempotent for already-accepted proposals: returns ``status:
    accepted`` instead of starting a new job, so the UI can treat the
    response identically to a successful poll. For a proposal open in the designer only
    when ``expectedRevision`` is the revision that was accepted.

    A proposal open in the Ontology designer is published as its draft instead (replace mode, not merged):
    the request must carry the ``expectedRevision`` the user reviewed. The refusals are 422
    ``ExpectedRevisionRequired``, 409 ``DraftConflict`` (the draft is at another revision, also
    when a change lands during the accept) and 409 ``RebaseRequired`` (a newer version exists).

    ``x_coa_principal`` (the percent-encoded ``X-Coa-Principal`` header the API proxy sets) is
    recorded as the version's author; in-process callers may pass it directly.
    """
    item = dynamo_store.get_proposal_by_id(proposal_id, namespace=namespace)
    if not item:
        raise HTTPException(404, f"Proposal '{proposal_id}' not found")
    status = item.get("status")
    if status == ProposalStatus.ACCEPTED.value:
        # Only a retry of the accept that published is idempotent: a designer caller reads the 202
        # as the publish of the revision it sent, which another tab's accept may have superseded.
        accepted_state = studio_draft.state_of(item)
        if accepted_state is not None:
            _check_expected_revision(accepted_state, body.expected_revision if body else None, "accept")
        return AcceptProposalResponse(proposal_id=proposal_id, status=ProposalStatus.ACCEPTED.value)
    if status == ProposalStatus.REJECTED.value:
        raise HTTPException(409, "Cannot accept a rejected proposal")
    if status in _ACCEPT_IN_PROGRESS_STATUSES:
        raise HTTPException(409, "Accept already in progress for this proposal")
    # ``accept_failed`` falls through to the accept path below — it is
    # re-acceptable, same as pending/updated: a failed publish changed nothing.

    # Prefer user-reviewed Turtle if the user revised the proposal. The R2RML (hydrated
    # from S3 by get_proposal_by_id) is merged into the version's mappings by the publish.
    turtle, r2rml_turtle = proposal_turtle(item, namespace)
    if not turtle:
        raise HTTPException(409, "Proposal has no ontology_turtle")

    explicit_target = body.ontology_id if body else None
    target_ontology_id = explicit_target or item.get("ontology_id", "")
    if not target_ontology_id:
        raise HTTPException(
            422,
            "Cannot determine target ontology_id: neither the request body nor the proposal carries one.",
        )

    # A delete of the target may already have dropped its graph; a version published
    # now would snapshot (and could deploy again) the ontology being deleted.
    if (dynamo_store.get_ontology_registry(namespace, target_ontology_id) or {}).get("status") == "deleting":
        raise HTTPException(409, f"Ontology '{target_ontology_id}' is being deleted; retry after the delete finishes.")

    # Guard: enforce one ontology per namespace (the product invariant — the UI
    # induces every source under a namespace-derived prefix, so all sources in a
    # namespace share one ontology_id and merge into a single VKG payload).
    #
    # A caller (direct API) *can* induce sources under DISTINCT
    # ``ontology_uri_prefix`` values, producing distinct ontology_ids in one
    # namespace. Accepting the second then used to OVERWRITE the first source's
    # per-namespace ``latest/`` VKG payload (single Ontop instance serves one
    # payload per namespace), silently breaking Tier-2 for the first source.
    # Rather than tolerate that by merging mismatched ontologies, reject it
    # loudly: a namespace holds exactly one induced ontology.
    #
    # The explicit ``body.ontology_id`` override is the deliberate
    # "merge this proposal into target ontology X" path — honoured as-is,
    # since the caller is naming the target on purpose.
    if explicit_target is None:
        # Scope to INDUCED ontologies only. Foundational/reference ontologies
        # (loaded for grounding) are also ONTOLOGY# registry rows, but they are
        # MEANT to coexist with the induced one — the invariant is "one *induced*
        # ontology per namespace". Without this filter, loading FIBO before the
        # first induction would make existing_ids non-empty and wrongly 409-reject
        # that first legitimate induced accept.
        existing_ids: set[str] = set()
        for o in dynamo_store.list_ontologies_registry(namespace, ontology_type="induced"):
            oid = o.get("ontology_id")
            if oid:
                existing_ids.add(str(oid))
        if existing_ids and target_ontology_id not in existing_ids:
            raise HTTPException(
                409,
                (
                    f"Namespace '{namespace}' already contains ontology "
                    f"'{sorted(existing_ids)[0]}'; a namespace holds exactly one induced "
                    f"ontology. This proposal was induced under a different ontology URI "
                    f"('{target_ontology_id}') and would overwrite the existing one's "
                    f"served mappings. Re-induce under the namespace's ontology prefix, "
                    f"or pass ontology_id explicitly to merge into the existing ontology."
                ),
            )

    # Every version in a namespace snapshots the same ontology id; an accept that
    # targets another id (even explicitly) would fork the version chain.
    head = version_registry.head_version(namespace)
    if head and head.get("ontology_id") != target_ontology_id:
        raise HTTPException(
            409,
            f"Namespace '{namespace}' publishes versions of ontology '{head['ontology_id']}'; "
            f"accept into that ontology id instead of '{target_ontology_id}'.",
        )

    publish_request = _publish_request(
        item,
        namespace,
        proposal_id,
        target_ontology_id,
        version_principal.caller(x_coa_principal),
        turtle,
        r2rml_turtle,
        title=_publish_title(item, namespace),
    )
    # A designer draft is published as it is (replace mode), and only the revision
    # the user reviewed, onto the version it was built on.
    studio_state = studio_draft.state_of(item)
    if studio_state is not None:
        publish_request = _studio_publish_request(
            namespace,
            proposal_id,
            studio_state,
            body.expected_revision if body else None,
            head,
            publish_request,
        )
    job_id = item["job_id"]
    deploy_after = body.deploy if body else True

    # Mark the proposal as accept-in-progress so concurrent UI polls + the
    # in-progress check above see the right state. Everything the worker needs
    # is built above, so nothing after this flip can fail and strand the
    # proposal in ``accepting``. Clear any stale
    # ``accept_error`` from a prior failed attempt at the same time. If
    # the worker fails, ``_accept_fail`` moves this to ``accept_failed``
    # with the new error (still re-acceptable).
    #
    # ``expected_status`` makes the transition atomic in DDB. The earlier
    # ``get → check → update`` sequence had a small race window: two
    # concurrent accepts both reading ``pending``, both writing
    # ``accepting``, both spawning workers. The conditional update
    # collapses that window — only one writer can transition the row,
    # the other gets ``ConditionalCheckFailedException`` which we
    # surface as 409 (same response the up-front check would have
    # returned). Cost: one extra ``ConditionExpression`` in the same
    # request, no extra round-trip.
    #
    # A designer draft is also pinned to the revision that was read above
    # (``expected_studio_revision``): a change that landed since makes the flip fail, and the
    # client gets ``DraftConflict`` with the revision the draft is at now, not the generic 409.
    try:
        dynamo_store.update_proposal(
            proposal_id,
            namespace=namespace,
            status="accepting",
            accept_error="",
            expected_status=status,
            expected_studio_revision=studio_state.revision if studio_state else None,
        )
    except ClientError as e:
        if e.response.get("Error", {}).get("Code") == "ConditionalCheckFailedException":
            if studio_state is not None:
                raise _studio_flip_lost(namespace, proposal_id) from e
            raise HTTPException(
                409,
                "Proposal status changed concurrently — refresh and retry",
            ) from e
        raise
    Thread(
        target=_run_publish_proposal,
        args=(proposal_id, namespace, publish_request, job_id, deploy_after),
        daemon=True,
    ).start()
    return AcceptProposalResponse(proposal_id=proposal_id, status="accepting")


@router.post("/{proposal_id}/cancel")
def cancel_proposal(proposal_id: str, namespace: str = "default"):
    """Cancel a pending/updated proposal so a new induction can proceed."""
    item = dynamo_store.get_proposal_by_id(proposal_id, namespace=namespace)
    if not item:
        raise HTTPException(404, f"Proposal '{proposal_id}' not found")
    # ``accept_failed`` is cancellable: before this state existed a failed accept
    # rolled back to ``pending``, so it was. The UI enables Cancel for it too
    # (isTerminal is only accepted/rejected/cancelled), so omitting it here would
    # 409 a button the user is invited to press. It is a reviewable, discardable
    # proposal like any other non-terminal one.
    if item.get("status") not in (
        ProposalStatus.PENDING.value,
        ProposalStatus.UPDATED.value,
        PROPOSAL_STATUS_ACCEPT_FAILED,
    ):
        raise HTTPException(409, f"Cannot cancel a {item.get('status')} proposal")
    dynamo_store.update_proposal(proposal_id, namespace=namespace, status=ProposalStatus.CANCELLED.value)
    studio_queries.drop_draft_graph_later(namespace, proposal_id)
    return {"proposal_id": proposal_id, "status": "cancelled"}


@router.post("/reject")
def reject_proposals(body: RejectRequest, namespace: str = "default"):
    """Reject one or many proposals with a reason."""
    results = []
    for pid in body.proposal_ids:
        item = dynamo_store.get_proposal_by_id(pid, namespace=namespace)
        if not item:
            results.append({"proposal_id": pid, "error": "not found"})
            continue
        if item.get("status") == ProposalStatus.ACCEPTED.value:
            results.append({"proposal_id": pid, "error": "already accepted"})
            continue
        dynamo_store.update_proposal(
            pid, namespace=namespace, status=ProposalStatus.REJECTED.value, reject_reason=body.reason
        )
        studio_queries.drop_draft_graph_later(namespace, pid)
        results.append({"proposal_id": pid, "status": "rejected"})
    return results


@router.post("/{proposal_id}/upload-url", response_model=ProposalUploadUrlResponse)
def get_proposal_upload_urls(proposal_id: str, namespace: str = "default"):
    """Presigned S3 PUT URLs for uploading edited proposal Turtle directly to S3.

    The mirror of the presigned-GET read path: lets the browser upload a large
    edited ontology / R2RML straight to S3, bypassing the 6 MB API Gateway /
    Lambda *request* cap. After uploading, the client calls ``POST /update``
    with ``ontology_uploaded`` / ``r2rml_uploaded`` set (instead of sending the
    Turtle inline).
    """
    item = dynamo_store.get_proposal_by_id(proposal_id, namespace=namespace, hydrate_turtle=False)
    if not item:
        raise HTTPException(404, f"Proposal '{proposal_id}' not found")
    if item.get("status") in (ProposalStatus.ACCEPTED.value, ProposalStatus.REJECTED.value):
        raise HTTPException(409, f"Cannot update a {item['status']} proposal")
    if item.get("studio"):
        raise HTTPException(409, _STUDIO_OPEN)
    revision_id = str(uuid.uuid4())
    version = f"revisions/{revision_id}"
    return ProposalUploadUrlResponse(
        revision_id=revision_id,
        ontology_put_url=dynamo_store.presign_proposal_artifact_put(
            namespace,
            proposal_id,
            "ontology",
            version=version,
        ),
        r2rml_put_url=dynamo_store.presign_proposal_artifact_put(
            namespace,
            proposal_id,
            "r2rml",
            version=version,
        ),
    )


@router.post("/update")
def update_proposal(body: UpdateProposalRequest, namespace: str = "default"):
    """Upload a modified proposal (user revision) or apply grounding overrides.

    When grounding choices are present, the backend patches the stored matches,
    re-fetches catalog tables, and rebuilds the Turtle + R2RML.
    Grounding overrides and direct Turtle edits must be submitted separately.
    """
    item = dynamo_store.get_proposal_by_id(body.proposal_id, namespace=namespace)
    if not item:
        raise HTTPException(404, f"Proposal '{body.proposal_id}' not found")
    if item.get("status") in (ProposalStatus.ACCEPTED.value, ProposalStatus.REJECTED.value):
        raise HTTPException(409, f"Cannot update a {item['status']} proposal")
    # The Ontology designer owns the draft of a proposal it opened; a Turtle or grounding edit here
    # would be silently ignored by the accept (which publishes the draft) or overwrite it.
    if item.get("studio"):
        raise HTTPException(409, _STUDIO_OPEN)

    has_turtle_update = any(
        (
            body.ontology_turtle is not None,
            body.r2rml_turtle is not None,
            body.ontology_uploaded,
            body.r2rml_uploaded,
        )
    )
    grounding_choices = body.grounding_choices
    if grounding_choices and (has_turtle_update or body.upload_revision_id is not None):
        raise HTTPException(400, "Grounding overrides and Turtle edits must be saved separately")
    if grounding_choices:
        try:
            return _apply_grounding_overrides(body.proposal_id, grounding_choices, item, namespace)
        except HTTPException as exc:
            if exc.status_code != 503:
                raise
            # ServiceUnavailableError is modeled as {"message": ...}; avoid
            # FastAPI's default {"detail": ...} envelope at this route boundary.
            return JSONResponse(status_code=503, content={"message": str(exc.detail)})

    # Turtle bodies are offloaded to S3 (only the S3 key is stored on the
    # DynamoDB item) — a large edited ontology written inline would trip the
    # 400 KB item limit, same failure mode as the grounding-override path.
    #
    # The edited Turtle arrives one of two ways:
    #   * inline ``*_turtle`` — fine for small ontologies, but the request
    #     itself is capped at the 6 MB API Gateway / Lambda limit; or
    #   * ``*_uploaded`` — the client PUT the artifact straight to its S3 key
    #     via a presigned URL (see ``get_proposal_upload_urls``), bypassing
    #     that request cap (the mirror of the presigned-GET read path). The
    #     server reads it back here to validate before committing the pointer.
    def _validate_turtle(ttl: str, what: str) -> None:
        from rdflib import Graph as RdfGraph

        try:
            RdfGraph().parse(data=ttl, format="turtle")
        except Exception as e:
            raise HTTPException(422, f"Invalid {what} Turtle: {e}") from e

    # NOTE: we deliberately do NOT canonicalize datatype tokens here. Editing a
    # proposal persists the user's Turtle verbatim — silently rewriting their
    # data at the write boundary is the anti-pattern this feature removes. Any
    # malformed/mis-cased/aliased token (xsd:datetime, xsd:varchar, …) is instead
    # surfaced by DatatypeTokenValidator at validation time and fixed only via the
    # consent-gated /repair-datatypes action. (The served VKG copy is still
    # sanitized at accept time in _clean_ontology_for_vkg, so a skipped repair
    # can't break Ontop queries.)
    has_uploaded_artifact = body.ontology_uploaded or body.r2rml_uploaded
    if has_uploaded_artifact and body.upload_revision_id is None:
        raise HTTPException(400, "uploadRevisionId is required when an uploaded flag is true")
    if not has_uploaded_artifact and body.upload_revision_id is not None:
        raise HTTPException(400, "uploadRevisionId is only valid with ontologyUploaded or r2rmlUploaded")

    if body.upload_revision_id is not None:
        try:
            revision_id = str(uuid.UUID(body.upload_revision_id))
        except (ValueError, AttributeError) as exc:
            raise HTTPException(400, "uploadRevisionId must be a UUID returned by the upload-url endpoint") from exc
    else:
        revision_id = str(uuid.uuid4())
    version = f"revisions/{revision_id}"
    updates: dict = {}

    if body.ontology_turtle is not None:
        _validate_turtle(body.ontology_turtle, "ontology")
        updates["ontology_s3_key"] = dynamo_store._put_artifact_s3(
            namespace,
            body.proposal_id,
            "ontology",
            body.ontology_turtle,
            version=version,
        )
    elif body.ontology_uploaded:
        ttl = dynamo_store._get_artifact_s3(namespace, body.proposal_id, "ontology", version=version)
        if ttl is None:
            raise HTTPException(400, "ontology_uploaded was set but no uploaded artifact was found in S3")
        _validate_turtle(ttl, "ontology")
        # Already stored at its key by the presigned upload; nothing to re-store.
        updates["ontology_s3_key"] = dynamo_store._proposal_s3_key(
            namespace,
            body.proposal_id,
            "ontology",
            version,
        )

    if body.r2rml_turtle is not None:
        _validate_turtle(body.r2rml_turtle, "R2RML")
        updates["r2rml_s3_key"] = dynamo_store._put_artifact_s3(
            namespace,
            body.proposal_id,
            "r2rml",
            body.r2rml_turtle,
            version=version,
        )
    elif body.r2rml_uploaded:
        ttl = dynamo_store._get_artifact_s3(namespace, body.proposal_id, "r2rml", version=version)
        if ttl is None:
            raise HTTPException(400, "r2rml_uploaded was set but no uploaded artifact was found in S3")
        _validate_turtle(ttl, "R2RML")
        updates["r2rml_s3_key"] = dynamo_store._proposal_s3_key(
            namespace,
            body.proposal_id,
            "r2rml",
            version,
        )

    if not updates:
        raise HTTPException(
            400,
            "Provide ontology_turtle/r2rml_turtle, ontology_uploaded/r2rml_uploaded, "
            "grounding_overrides, or novel_tables",
        )

    updates["status"] = "updated"
    updates["revision_id"] = revision_id
    dynamo_store.update_proposal(body.proposal_id, namespace=namespace, **updates)

    return {"proposal_id": body.proposal_id, "status": "updated"}


class RepairDatatypesRequest(BaseModel):
    """Request body for ``POST /proposals/{id}/repair-datatypes``."""

    # When True, compute + return the changes WITHOUT persisting them. Used by the
    # accept-time guard to check "does this proposal have unrepaired datatype
    # issues?" cheaply, without a reasoner run and without mutating anything.
    dry_run: bool = False
    # Required to repair a proposal open in the Ontology designer: the draft revision the user reviewed.
    expected_revision: int | None = Field(default=None, alias="expectedRevision", ge=0, le=studio_draft.MAX_REVISION)

    model_config = ConfigDict(populate_by_name=True)


class RepairDatatypesResponse(BaseModel):
    """Result of a datatype-repair run (or preview, when ``dry_run``)."""

    proposal_id: str
    repaired_count: int
    changes: list[dict[str, str]]
    # Echoes the request mode so a client can distinguish "would repair N" (preview)
    # from "repaired N" (applied) off a single shape.
    dry_run: bool = False
    # Only for a repair applied to a designer draft: the draft's revision after it (unchanged
    # when there was nothing to repair).
    revision: int | None = None


@router.post(
    "/{proposal_id}/repair-datatypes", response_model=RepairDatatypesResponse, response_model_exclude_none=True
)
def repair_proposal_datatypes(
    proposal_id: str,
    body: RepairDatatypesRequest | None = None,
    namespace: str = "default",
    x_coa_principal: Annotated[str | None, Header()] = None,
) -> RepairDatatypesResponse:
    """Repair (or, with ``dry_run``, preview) malformed XSD datatype tokens.

    User-initiated, consent-gated counterpart to the DatatypeTokenValidator
    finding: the validator surfaces the offending tokens at validation time and
    the user invokes this to apply the fix (replacing the previous silent
    write-boundary canonicalization). Rewrites the stored ontology Turtle AND the
    R2RML mappings, since a malformed ``rr:datatype`` is copied into the served
    ontology range at accept. Server-authoritative: the canonical XSD map lives
    here, not in the client. Idempotent — a clean proposal returns
    ``repaired_count: 0`` and persists nothing.

    ``dry_run=true`` computes the same change list but persists NOTHING (and does
    not flip status) — the accept-time guard uses it to detect unrepaired tokens
    before an accept without mutating the proposal.

    A proposal open in the Ontology designer is repaired in its draft, not in the stored Turtle: the same
    change list is computed over the draft's current revision, and a repair (not ``dry_run``) applies
    it as one change set of ``replace_datatype`` ops, a new revision that can be undone. It needs the
    ``expectedRevision`` the user reviewed (422 ``ExpectedRevisionRequired``, 409 ``DraftConflict``),
    refuses a proposal that left review (409 ``ProposalNotEditable``), and answers with the draft's
    ``revision`` afterwards. With nothing to repair nothing is written.
    """
    from coa_ontology.datatype_canonicalizer import canonicalize_turtle

    dry_run = bool(body and body.dry_run)

    item = dynamo_store.get_proposal_by_id(proposal_id, namespace=namespace)
    if not item:
        raise HTTPException(404, f"Proposal '{proposal_id}' not found")
    status = item.get("status")
    # Only the mutating path is state-gated; a dry-run preview is read-only and
    # safe on any status.
    if not dry_run and status in (ProposalStatus.ACCEPTED.value, ProposalStatus.REJECTED.value):
        raise HTTPException(409, f"Cannot repair a {status} proposal")

    changes: list[tuple[str, str]] = []
    pending_artifacts: dict[str, str] = {}
    ontology_ttl = item.get("ontology_turtle") or ""
    r2rml_ttl = item.get("r2rml_turtle") or ""
    studio = studio_draft.state_of(item)
    if studio is not None:
        if not dry_run:
            try:
                studio_draft.require_state(item, editable=True)
            except studio_draft.StudioError as e:
                raise _studio_http(e) from e
            _check_expected_revision(studio, body.expected_revision if body else None, "repair")
        ontology_ttl, r2rml_ttl = studio_draft.revision_text(namespace, proposal_id, studio.revision)
    # The stored Turtle is rewritten only for a proposal the Ontology designer has not opened.
    persist = not dry_run and studio is None

    def _canonicalize_or_422(ttl: str, what: str) -> tuple[str, list[tuple[str, str]]]:
        # canonicalize_turtle is a pure util that lets an rdflib ParserError
        # propagate. Stored Turtle is normally validated on write (update_proposal
        # -> _validate_turtle 422s on parse failure), so this only fires on
        # out-of-band corruption (manual DDB/S3 edit, truncated object). Convert it
        # to an actionable 422 — matching _validate_turtle — instead of a 500 +
        # traceback, and so the accept-time guard's dry_run call doesn't surface a 500.
        try:
            return canonicalize_turtle(ttl)
        except Exception as e:
            raise HTTPException(422, f"Stored {what} Turtle is not parseable: {e}") from e

    if ontology_ttl:
        canonical, onto_changes = _canonicalize_or_422(ontology_ttl, "ontology")
        if onto_changes:
            if persist:
                pending_artifacts["ontology"] = canonical
            changes.extend(onto_changes)

    if r2rml_ttl:
        canonical_r2rml, r2rml_changes = _canonicalize_or_422(r2rml_ttl, "R2RML")
        if r2rml_changes:
            if persist:
                pending_artifacts["r2rml"] = canonical_r2rml
            changes.extend(r2rml_changes)

    if pending_artifacts:  # only populated on the non-dry-run path
        revision_id = str(uuid.uuid4())
        version = f"revisions/{revision_id}"
        updates: dict[str, Any] = {
            f"{artifact}_s3_key": dynamo_store._put_artifact_s3(
                namespace,
                proposal_id,
                artifact,
                content,
                version=version,
            )
            for artifact, content in pending_artifacts.items()
        }
        updates["revision_id"] = revision_id
        updates["status"] = "updated"
        dynamo_store.update_proposal(proposal_id, namespace=namespace, **updates)
        _log.info("Repaired %d datatype token(s) on proposal %s: %s", len(changes), proposal_id, changes)

    revision: int | None = None
    if studio is not None and not dry_run:
        revision = studio.revision
        if changes:
            # One op per token: it replaces every use, so the pairs of a token's many uses collapse.
            ops = [
                {"op": "replace_datatype", "from": found, "to": canonical}
                for found, canonical in dict.fromkeys(changes)
            ]
            try:
                revision = studio_changes.apply_change_set(
                    namespace, proposal_id, ops, studio.revision, author=version_principal.caller(x_coa_principal)
                )["revision"]
            except studio_draft.StudioError as e:
                raise _studio_http(e) from e
            _log.info(
                "Repaired %d datatype token(s) in the draft of proposal %s: %s", len(changes), proposal_id, changes
            )

    return RepairDatatypesResponse(
        proposal_id=proposal_id,
        repaired_count=len(changes),
        changes=[{"found": before, "canonical": after} for before, after in changes],
        dry_run=dry_run,
        revision=revision,
    )


def _grounding_override_key(
    match: "ConceptMatch",
    overrides: dict[str, str | None],
    table_match_counts: Counter[str],
) -> str | None:
    """Pick an exact identity key, or a safe unique-table legacy key."""
    candidate_keys = [match.source_table_identity] if match.source_table_identity else []
    if table_match_counts[match.source_table] == 1:
        candidate_keys.append(match.source_table)
    return next((key for key in candidate_keys if key in overrides), None)


def _apply_grounding_overrides(proposal_id: str, overrides: dict[str, str | None], item: dict, namespace: str) -> dict:
    """Patch grounding matches and rebuild Turtle + R2RML."""
    import os

    from coa_ontology.induce_catalog import _catalog_to_tables, fetch_datasource_catalog
    from coa_ontology.inducer.schemas import ConceptMatch
    from coa_ontology.inducer.services.data_catalog import CatalogTable
    from coa_ontology.inducer.services.grounding import classify_score_tier
    from coa_ontology.inducer.strategies.base import schema_from_fqn
    from coa_ontology.inducer.strategies.table_to_ontology import TableToOntologyStrategy

    meta = item.get("metadata") or {}
    raw_matches = meta.get("matches") or []
    if not raw_matches:
        raise HTTPException(409, "Proposal has no grounding matches to update")

    matches = [ConceptMatch(**m) if isinstance(m, dict) else m for m in raw_matches]
    table_match_counts = Counter(m.source_table for m in matches if not m.source_column)

    # Validate every requested key and URI before mutating any match, so a bad
    # request cannot change metadata for one match while Turtle points at
    # another class. Keys resolve through _grounding_override_key (stable table
    # identity first, a bare table name only while it is unique). A key that
    # names no class-level match fails closed, and so does a bare name that
    # several class-level matches share: the caller asked for one table and the
    # key cannot say which, so the whole request is rejected rather than
    # applying the choice to no table and reporting success.
    class_matches = [m for m in matches if not m.source_column]
    identity_keys = {m.source_table_identity for m in class_matches if m.source_table_identity}
    known_override_keys = {m.source_table for m in class_matches} | identity_keys
    for override_key, override_uri in overrides.items():
        if override_key not in known_override_keys:
            raise HTTPException(
                409,
                f"Grounding override key '{override_key}' does not identify a class-level proposal match",
            )
        if override_key not in identity_keys and table_match_counts[override_key] > 1:
            raise HTTPException(
                409,
                (
                    f"Grounding override key '{override_key}' is ambiguous: "
                    f"{table_match_counts[override_key]} class-level proposal matches share that table name; "
                    "key the override by the table's source identity instead"
                ),
            )
        if override_uri is None:
            continue
        try:
            scheme = urlsplit(override_uri).scheme.lower()
        except ValueError:
            scheme = ""
        if (
            not override_uri
            or len(override_uri) > 2048
            or not override_uri.isprintable()
            or any(character.isspace() for character in override_uri)
            or scheme not in ("http", "https")
        ):
            raise HTTPException(
                409,
                (
                    f"Grounding override for '{override_key}' must be an HTTP(S) URI "
                    "of at most 2048 printable non-whitespace characters"
                ),
            )
    # A chosen URI must be one of the stored candidates of the match its key
    # actually resolves to (identity first, unique bare name second).
    for m in class_matches:
        match_key = _grounding_override_key(m, overrides, table_match_counts)
        if match_key is None or overrides[match_key] is None:
            continue
        candidate_uris = {candidate.entity_uri for candidate in m.candidates or []}
        if overrides[match_key] not in candidate_uris:
            raise HTTPException(
                409,
                f"Grounding override for '{match_key}' must select one of the proposal's stored candidates",
            )

    for m in matches:
        if m.source_column:
            continue
        match_key = _grounding_override_key(m, overrides, table_match_counts)
        if match_key is None:
            continue

        # Relationship and rationale describe the previously selected target.
        # Candidates retain identity and scores but not their own reranker
        # relationship/reason, so reusing either field after an override would
        # attach stale RDF semantics and UI rationale to the new target. Clear
        # both for every explicit choice and let RDF emission fall back to the
        # reclassified match_type below.
        m.relationship = None
        m.reason = None
        override_uri = overrides[match_key]
        if override_uri is None:
            m.matched_class_uri = None
            m.matched_ontology_id = None
            m.match_type = "novel"
            m.similarity = None
        else:
            m.matched_class_uri = override_uri
            # Derive the tier from the chosen candidate's own score rather than
            # hardcoding "high_confidence". Hardcoding was lossy and wrong: an
            # original *exact* match (e.g. publication → Publication @ 0.95)
            # demoted to high_confidence on the first override and never
            # recovered — even when the user reverted to that same candidate.
            # Each stored candidate keeps its score, so re-classifying with the
            # grounding service's own thresholds makes overrides round-trip:
            # reverting to the original grounding restores its original tier.
            cand = None
            if m.candidates:
                cand = next((c for c in m.candidates if c.entity_uri == override_uri), None)
            if cand:
                m.matched_ontology_id = cand.ontology_id
                # GroundingService stores the LLM confidence only on the one
                # ENHANCED candidate that was actually reranked. Alternate
                # candidates (and every STANDARD candidate) retain lexical_sim
                # only, so their score must use the embedding ladder instead of
                # being interpreted as an LLM confidence. The parent strategy
                # check also avoids treating another producer's fused score as a
                # grounding rerank score.
                has_rerank = m.scoring_strategy == "grounding_enhanced" and cand.fused_score is not None
                score = cand.fused_score if has_rerank else cand.lexical_sim
                m.similarity = score
                m.match_type = classify_score_tier(score, has_rerank=has_rerank)
            else:  # pragma: no cover - validated before mutation
                raise RuntimeError(f"validated grounding candidate disappeared for {m.source_table!r}")

    uri_prefix = item.get("ontology_id") or meta.get("ontology_uri_prefix", "http://example.org/ind#")

    # ── Unstructured branch ──────────────────────────────────────────────
    # Unstructured proposals have no DB catalog tables to rebuild from — their
    # ontology is the induced lexical-graph Turtle. Re-apply the (already
    # patched) grounding matches by surgically rewriting the grounding axioms
    # on the stored Turtle, rather than running the structured table rebuild
    # (which would 409 on 'no catalog tables'). No R2RML for unstructured.
    if item.get("source_type") == "UNSTRUCTURED":
        from coa_ontology.inducer.unstructured.services.class_grounding import (
            apply_overrides_to_turtle,
        )

        stored_turtle = item.get("ontology_turtle") or ""
        if not stored_turtle and item.get("ontology_s3_key"):
            stored_turtle = dynamo_store._get_s3_text(item["ontology_s3_key"]) or ""
        if not stored_turtle:
            # Legacy/unit-test fallback for proposal rows that predate pointers.
            stored_turtle = dynamo_store._get_artifact_s3(namespace, proposal_id, "ontology") or ""
        if not stored_turtle:
            raise HTTPException(409, "Proposal has no stored ontology Turtle to patch")

        overridden_matches = [
            match
            for match in matches
            if not match.source_column and _grounding_override_key(match, overrides, table_match_counts) is not None
        ]
        try:
            new_turtle, grounded_count = apply_overrides_to_turtle(
                stored_turtle,
                overridden_matches,
                uri_prefix=uri_prefix,
            )
        except ValueError as exc:
            # Matches were patched only in memory. Abort before writing either
            # metadata or Turtle so an unresolved class cannot create
            # split-brain proposal state.
            raise HTTPException(409, f"Grounding override could not be applied: {exc}") from exc

        from coa_ontology.induce_catalog import _floats_to_decimal

        updated_matches = [m.model_dump() for m in matches if not m.source_column]
        revision_id = str(uuid.uuid4())
        version = f"revisions/{revision_id}"
        matches_s3_key = dynamo_store.put_proposal_matches_s3(
            proposal_id,
            updated_matches,
            namespace=namespace,
            version=version,
        )
        meta_stripped = {k: v for k, v in meta.items() if k not in ("matches", "constraint_config")}
        meta_stripped["foundational_grounded_count"] = grounded_count
        onto_key = dynamo_store._put_artifact_s3(
            namespace,
            proposal_id,
            "ontology",
            new_turtle,
            version=version,
        )
        dynamo_store.update_proposal(
            proposal_id,
            namespace=namespace,
            ontology_s3_key=onto_key,
            matches_s3_key=matches_s3_key,
            status=ProposalStatus.UPDATED.value,
            metadata=_floats_to_decimal(meta_stripped),
            revision_id=revision_id,
        )
        return {"proposal_id": proposal_id, "status": "updated"}

    # ── Structured branch (rebuild from DB catalog tables) ───────────────
    ds_ids = meta.get("datasource_ids") or []
    catalog_source = os.environ.get("CATALOG_SOURCE", "http")
    config = {
        "catalog_source": catalog_source,
        "data_catalog_url": os.environ.get("DATA_CATALOG_URL", ""),
        "smus_domain_id": os.environ.get("SMUS_DOMAIN_ID", ""),
        "namespaces_table": os.environ.get("NAMESPACES_TABLE", ""),
        "smus_datasources_table": os.environ.get("DATASOURCES_TABLE", ""),
        "sources_table": os.environ.get("SOURCES_TABLE", ""),
        "smus_region": os.environ.get("AWS_REGION", "us-east-1"),
    }

    all_tables: list[CatalogTable] = []
    for ds_id in ds_ids:
        try:
            # The same resolution as induction, including the bundled fixture for a
            # ``-mock`` datasource: a proposal induced from one must be editable too.
            catalog = fetch_datasource_catalog(config, ds_id, namespace=namespace)
            for tbl_dict in _catalog_to_tables(catalog):
                tbl_dict["datasourceId"] = ds_id
                # schema_from_fqn, not fqn.split(".")[0]: the schema is the segment
                # NEAREST the table. A 3-part catalog.database.table FQN would else
                # stamp the CATALOG here — and this value is coa:sourceSchema, which
                # must MATCH the schema _generate_schema_sql derives (also via
                # schema_from_fqn) or the R2RML mapping and the H2 validation schema
                # qualify a shared-name table on different segments and Ontop rejects
                # the mapping at VKG load.
                tbl_dict["sourceSchema"] = schema_from_fqn(tbl_dict.get("fullyQualifiedName")) or None
                all_tables.append(CatalogTable(**tbl_dict))
        except Exception as e:
            _log.warning("Failed to fetch catalog for %s: %s", ds_id, e)
            raise HTTPException(
                503,
                f"Could not fetch catalog for datasource '{ds_id}'; no grounding changes were saved",
            ) from e

    if not all_tables:
        raise HTTPException(409, "Could not fetch catalog tables for this proposal's datasources")

    # The rebuild regenerates the whole proposal ontology, so it needs the same
    # namespace language the induction used. The language is immutable, so the
    # namespace item is the authority here too.
    from coa_ontology.induce_catalog import namespace_language_or_404

    namespace_language = namespace_language_or_404(namespace, config)
    strategy = TableToOntologyStrategy()
    proposal_graph, novel_tables = strategy._build_proposal_ontology(
        uri_prefix, all_tables, matches, namespace_language=namespace_language
    )
    r2rml_graph = strategy.build_r2rml(
        ontology_uri_prefix=uri_prefix,
        tables=all_tables,
        novel_tables=novel_tables,
        proposal_graph=proposal_graph,
    )

    ontology_ttl = proposal_graph.serialize(format="turtle")
    r2rml_ttl = r2rml_graph.serialize(format="turtle")

    from coa_ontology.induce_catalog import _floats_to_decimal

    # Matches are serialized to S3 as JSON, so they keep native floats — NOT
    # ``_floats_to_decimal`` (which is only for inline DynamoDB attributes;
    # ``Decimal`` is not JSON-serializable and would break ``json.dumps``).
    updated_matches = [m.model_dump() for m in matches if not m.source_column]
    # Offload matches to S3 (they exceed the DynamoDB 400 KB item limit once
    # candidates + definitions are included) and persist only the S3 key on the
    # item — mirroring create_proposal. Writing them inline into ``metadata``
    # fails with "Item size has exceeded the maximum allowed size for :metadata".
    revision_id = str(uuid.uuid4())
    version = f"revisions/{revision_id}"
    matches_s3_key = dynamo_store.put_proposal_matches_s3(
        proposal_id,
        updated_matches,
        namespace=namespace,
        version=version,
    )
    # Strip blobs that live in S3 from the inline metadata before the write:
    #   - ``matches``: re-persisted to S3 above (matches_s3_key).
    #   - ``constraint_config``: get_proposal_by_id hydrates it INTO metadata
    #     from S3 (flagged by ``has_constraint_config``); writing it back inline
    #     would re-bloat the item. The S3 copy is untouched, so dropping the
    #     inline copy keeps the flag-driven hydration working.
    meta_stripped = {k: v for k, v in meta.items() if k not in ("matches", "constraint_config")}
    # Turtle is offloaded to S3 too; pass the keys, not the bodies.
    onto_key = dynamo_store._put_artifact_s3(
        namespace,
        proposal_id,
        "ontology",
        ontology_ttl,
        version=version,
    )
    r2rml_key = dynamo_store._put_artifact_s3(
        namespace,
        proposal_id,
        "r2rml",
        r2rml_ttl,
        version=version,
    )
    dynamo_store.update_proposal(
        proposal_id,
        namespace=namespace,
        ontology_s3_key=onto_key,
        r2rml_s3_key=r2rml_key,
        matches_s3_key=matches_s3_key,
        status=ProposalStatus.UPDATED.value,
        metadata=_floats_to_decimal(meta_stripped),
        revision_id=revision_id,
    )

    return {"proposal_id": proposal_id, "status": "updated"}


